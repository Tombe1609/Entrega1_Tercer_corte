const router=require('express').Router();
const asyncHandler=require('../utils/asyncHandler');
const c=require('../controllers/productos.controller');
const requireRole=require('../middlewares/requireRole');
const { requireArea } = require('../middlewares/requireArea');
router.get('/',(req,res,next)=>req.auth.rol==='estudiante' ? next() : requireArea('creditos')(req,res,next),asyncHandler(c.listar));
router.get('/compras/mias',requireRole('estudiante'),asyncHandler(c.misCompras));
router.post('/',requireArea('creditos'),asyncHandler(c.crear));
router.patch('/:producto_id',requireArea('creditos'),asyncHandler(c.actualizar));
router.patch('/:producto_id/estado',requireArea('creditos'),asyncHandler(c.cambiarEstado));
router.post('/:producto_id/compras',requireRole('estudiante'),asyncHandler((req,res)=>{req.body={...req.body,producto_id:req.params.producto_id};return c.comprar(req,res);}));
module.exports=router;
